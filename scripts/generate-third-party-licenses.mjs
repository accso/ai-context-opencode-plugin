#!/usr/bin/env node
/**
 * Generates THIRD-PARTY-LICENSES.md: the third-party code that IS shipped inside our artifacts
 * (inlined into dist/accso-ai-context.js / ai-context-worker.mjs), with full license texts because
 * redistribution requires them. The bundled set is detected from esbuild's metafile, so it cannot
 * drift from the build. Software we only use (installed from npm or downloaded at runtime) is not
 * redistributed and not listed.
 *
 * `npm run licenses` writes the file, `npm run licenses:check` fails when it is out of date.
 * Requires `npm install` first (reads node_modules).
 */
import { execSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";
import { EXTERNAL_RUNTIME_DEPS } from "./bundle-config.mjs";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const check = process.argv.includes("--check");

const ENTRIES = ["src/index.ts", "src/worker/worker-main.ts"]; // same entries as scripts/build.mjs

async function bundledPackageNames() {
  const names = new Set();
  for (const entry of ENTRIES) {
    const r = await build({
      entryPoints: [path.join(root, entry)],
      write: false,
      metafile: true,
      bundle: true,
      platform: "node",
      format: "esm",
      target: "node18",
      external: [...EXTERNAL_RUNTIME_DEPS, "@opencode-ai/plugin"],
      logLevel: "silent",
    });
    for (const file of Object.keys(r.metafile.inputs)) {
      const m = file.match(/node_modules\/((?:@[^/]+\/)?[^/]+)/);
      if (m) names.add(m[1]);
    }
  }
  return names;
}

function readPackages() {
  const dirs = execSync("npm ls --omit=dev --all --parseable", { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] })
    .split("\n")
    .filter(Boolean)
    .filter((p) => p !== root);
  const pkgs = new Map();
  for (const dir of dirs) {
    let j;
    try {
      j = JSON.parse(fs.readFileSync(path.join(dir, "package.json"), "utf8"));
    } catch {
      continue;
    }
    let license = j.license ?? (Array.isArray(j.licenses) ? j.licenses.map((l) => l.type).join(" OR ") : undefined) ?? "UNKNOWN";
    if (typeof license === "object") license = license.type;
    const files = fs.readdirSync(dir).filter((f) => /^(licen[sc]e|copying)/i.test(f) && fs.statSync(path.join(dir, f)).isFile());
    const text = files.length ? fs.readFileSync(path.join(dir, files[0]), "utf8").replace(/\r\n/g, "\n").trim() : undefined;
    const repo = typeof j.repository === "string" ? j.repository : j.repository?.url;
    pkgs.set(`${j.name}@${j.version}`, {
      name: j.name,
      version: j.version,
      license,
      text,
      repo: repo?.replace(/^git\+/, "").replace(/\.git$/, ""),
    });
  }
  return [...pkgs.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
}

const HEADER = "<!-- generated by scripts/generate-third-party-licenses.mjs; do not edit by hand (npm run licenses) -->";

function shippedFile(shipped) {
  const out = ["# Third-party licenses (code shipped with the plugin)", "", HEADER, ""];
  out.push("ai-context-opencode-plugin is licensed under the Apache License 2.0 (see [LICENSE](LICENSE) and [NOTICE](NOTICE)).");
  out.push("The plugin bundle (`accso-ai-context.js`) contains the third-party code below, inlined at build time. Its license terms apply to the bundle and must travel with it.");
  out.push("| Package | Version | License | Source |", "| --- | --- | --- | --- |");
  for (const p of shipped) out.push(`| ${p.name} | ${p.version} | ${p.license} | ${p.repo ?? ""} |`);
  out.push("", "## License texts", "");
  for (const p of shipped) {
    out.push(`### ${p.name}@${p.version} (${p.license})`, "");
    out.push(p.text ? "```text\n" + p.text + "\n```" : "_No license file in the package; the license is declared in its `package.json`._", "");
  }
  return out;
}

const bundled = await bundledPackageNames();
const all = readPackages();
const shipped = all.filter((p) => bundled.has(p.name));
const missing = [...bundled].filter((n) => !shipped.some((p) => p.name === n));
if (missing.length) {
  console.error(`Bundled but not in the production dependency tree: ${missing.join(", ")}`);
  process.exit(2);
}

const render = (lines) => lines.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd() + "\n";
const files = { "THIRD-PARTY-LICENSES.md": render(shippedFile(shipped)) };

let stale = false;
for (const [name, content] of Object.entries(files)) {
  const file = path.join(root, name);
  if (check) {
    if ((fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "") !== content) {
      console.error(`${name} is out of date: run \`npm run licenses\`.`);
      stale = true;
    }
  } else {
    fs.writeFileSync(file, content);
  }
}
if (check) {
  if (stale) process.exit(1);
  console.log("THIRD-PARTY-LICENSES.md is up to date.");
} else {
  console.log(`Shipped (bundled): ${shipped.map((p) => `${p.name}@${p.version}`).join(", ")}`);
}
