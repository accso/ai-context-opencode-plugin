import { appendFileSync, mkdirSync, readdirSync, readFileSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { basename, dirname, join } from "node:path";

/**
 * Opt-in (`tool_log: true`) protocol of every tool call, human-readable, in
 * `.opencode/ai-context/tool.log.md`: when which tool was asked with which
 * arguments, and what came back. By default only a short summary of the
 * response is written (size, counts, first paths, error); the response text
 * itself needs `tool_log_full_responses: true`; then arguments and responses are
 * written without any truncation (otherwise arguments are cut at 200 chars). At
 * `maxBytes` the file is renamed to `tool.<timestamp>.log.md` and a new one is
 * started; only the newest `maxRotatedFiles` rotated files are kept. Never throws.
 */
export interface ToolCall {
  tool: string;
  sessionID: string;
  callID: string;
}

export interface ToolLog {
  request(call: ToolCall & { args: unknown }): void;
  response(call: ToolCall & { output: unknown }): void;
}

export interface ToolLogOptions {
  filePath: string;
  now?: () => Date;
  /** Size at which the file is rotated. Default 5 MB. */
  maxBytes?: number;
  maxRotatedFiles?: number;
  /** Also write the complete response text, not only its summary. */
  fullResponses?: boolean;
}

const HEADER =
  "# Tool log\n\n<!-- generated by ai-context-opencode-plugin; newest entries last, oldest are dropped -->\n";
const DEFAULT_MAX_BYTES = 5 * 1024 * 1024;
const DEFAULT_MAX_ROTATED = 10;
const MAX_ARG_CHARS = 200;
const MAX_LISTED = 3;

function truncate(text: string, max: number): string {
  return text.length > max ? `${text.slice(0, max)}… (+${text.length - max} chars)` : text;
}

function formatArgs(args: unknown, full = false): string {
  try {
    if (full) return JSON.stringify(args) ?? "";
    return JSON.stringify(args, (_key, value) =>
      typeof value === "string" ? truncate(value, MAX_ARG_CHARS) : value,
    ) ?? "";
  } catch {
    return "(arguments not serializable)";
  }
}

/** One-line-per-fact digest of a tool response, without its content. */
export function summarizeResponse(output: unknown): string {
  const text = typeof output === "string" ? output : (formatArgs(output) ?? "");
  if (text.trim() === "") return "- empty response";
  const lines = [`- ${text.length} chars`];
  let parsed: unknown;
  try {
    parsed = JSON.parse(text);
  } catch {
    lines.push(`- starts with: ${truncate(text.split("\n")[0]!, 120)}`);
    return lines.join("\n");
  }
  const record = parsed && typeof parsed === "object" ? (parsed as Record<string, unknown>) : {};
  if (typeof record.error === "string") lines.push(`- error: ${truncate(record.error, 200)}`);
  const lists = Array.isArray(parsed)
    ? [["items", parsed] as const]
    : Object.entries(record).filter((entry): entry is [string, unknown[]] => Array.isArray(entry[1]));
  let total = 0;
  for (const [name, list] of lists) {
    total += list.length;
    const paths = list
      .map((item) => (item && typeof item === "object" ? (item as Record<string, unknown>).path : undefined))
      .filter((p): p is string => typeof p === "string")
      .slice(0, MAX_LISTED);
    lines.push(`- ${name}: ${list.length}${paths.length ? ` (${paths.join(", ")})` : ""}`);
  }
  if (lists.length > 0 && total === 0) lines.push("- empty result");
  return lines.join("\n");
}

export function createToolLog(options: ToolLogOptions): ToolLog {
  const now = options.now ?? (() => new Date());
  const maxBytes = options.maxBytes ?? DEFAULT_MAX_BYTES;
  const maxRotated = options.maxRotatedFiles ?? DEFAULT_MAX_ROTATED;
  const stem = basename(options.filePath).replace(/\.log\.md$/, "");
  const isRotated = (name: string) => name.startsWith(`${stem}.`) && name.endsWith(".log.md") && name !== basename(options.filePath);
  const started = new Map<string, number>();

  const rotate = () => {
    const dir = dirname(options.filePath);
    const stamp = now().toISOString().replace(/[:.]/g, "-");
    let target = join(dir, `${stem}.${stamp}.log.md`);
    for (let n = 1; readdirSync(dir).includes(basename(target)); n++) target = join(dir, `${stem}.${stamp}-${n}.log.md`);
    renameSync(options.filePath, target);
    const old = readdirSync(dir).filter(isRotated).sort();
    for (const name of old.slice(0, Math.max(0, old.length - maxRotated))) rmSync(join(dir, name), { force: true });
  };

  const write = (entry: string) => {
    try {
      mkdirSync(dirname(options.filePath), { recursive: true });
      let current = "";
      try {
        current = readFileSync(options.filePath, "utf8");
      } catch {
        // first write
      }
      if (!current.startsWith("# Tool log")) current = HEADER;
      if (current !== HEADER && Buffer.byteLength(current + entry) > maxBytes) {
        rotate();
        current = HEADER;
      }
      if (current === HEADER) writeFileSync(options.filePath, HEADER + entry);
      else appendFileSync(options.filePath, entry);
    } catch {
      // logging must never break the plugin
    }
  };

  const title = (at: Date, prefix: string, call: ToolCall, suffix = "") =>
    `\n## ${at.toISOString()} — ${prefix}${call.tool} (session ${call.sessionID}, call ${call.callID})${suffix}\n`;

  return {
    request(call) {
      const at = now();
      started.set(call.callID, at.getTime());
      write(`${title(at, "", call)}\n\`\`\`json\n${formatArgs(call.args, options.fullResponses)}\n\`\`\`\n`);
    },
    response(call) {
      const at = now();
      const begin = started.get(call.callID);
      started.delete(call.callID);
      const duration = begin === undefined ? "" : ` +${at.getTime() - begin} ms`;
      let entry = `${title(at, "↳ ", call, duration)}\n${summarizeResponse(call.output)}\n`;
      if (options.fullResponses) {
        const text = typeof call.output === "string" ? call.output : formatArgs(call.output);
        entry += `\n\`\`\`\n${text}\n\`\`\`\n`;
      }
      write(entry);
    },
  };
}
