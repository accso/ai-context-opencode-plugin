import { appendFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";

/**
 * Persistent, human-readable record of everything that went wrong
 * (`.opencode/ai-context/error.log.md`). Entries are buffered until
 * `activate()` so a disabled plugin writes nothing; the file is capped by
 * dropping the oldest entries. Never throws.
 */
export interface ErrorLog {
  record(context: string, error?: unknown): void;
  /** Start writing; flushes entries recorded before. */
  activate(): void;
}

export interface ErrorLogOptions {
  filePath: string;
  now?: () => Date;
  maxBytes?: number;
}

const HEADER =
  "# Error log\n\n<!-- generated by ai-context-opencode-plugin; newest entries last, oldest are dropped -->\n";
const DEFAULT_MAX_BYTES = 256 * 1024;
const MAX_BUFFERED = 100;

export function createErrorLog(options: ErrorLogOptions): ErrorLog {
  const now = options.now ?? (() => new Date());
  const maxBytes = options.maxBytes ?? DEFAULT_MAX_BYTES;
  let active = false;
  let buffer: string[] = [];

  const write = (entry: string) => {
    try {
      mkdirSync(dirname(options.filePath), { recursive: true });
      let current = "";
      try {
        current = readFileSync(options.filePath, "utf8");
      } catch {
        // first write
      }
      if (!current.startsWith("# Error log")) current = HEADER;
      let next = current + entry;
      if (Buffer.byteLength(next) > maxBytes) {
        const entries = next.slice(HEADER.length).split(/(?=\n## )/);
        while (entries.length > 1 && Buffer.byteLength(HEADER + entries.join("")) > maxBytes) entries.shift();
        next = HEADER + entries.join("");
        writeFileSync(options.filePath, next);
      } else if (current === HEADER) {
        writeFileSync(options.filePath, next);
      } else {
        appendFileSync(options.filePath, entry);
      }
    } catch {
      // logging must never break the plugin
    }
  };

  const format = (context: string, error?: unknown) => {
    const detail =
      error === undefined ? "" : error instanceof Error ? (error.stack ?? error.message) : String(error);
    return `\n## ${now().toISOString()} — ${context}\n${detail ? `\n\`\`\`\n${detail}\n\`\`\`\n` : ""}`;
  };

  return {
    record(context, error) {
      const entry = format(context, error);
      if (active) write(entry);
      else if (buffer.length < MAX_BUFFERED) buffer.push(entry);
    },
    activate() {
      if (active) return;
      active = true;
      for (const entry of buffer) write(entry);
      buffer = [];
    },
  };
}
