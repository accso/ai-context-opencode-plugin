import { tool } from "./tool-def.js";
import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { basename, dirname } from "node:path";
import type { IndexedFile, IndexStatus } from "../storage/vector-store.js";

export interface IndexTreeMeta {
  repoName: string;
  repoPath: string;
  branch: string;
  commit: string;
  exportedAt: string;
  newestIndexedAt: string | null;
  chunkCount: number;
  skipped: string[];
}

export interface GitInfo {
  branch: string;
  commit: string;
}

export interface IndexTreeDeps {
  filePath: string;
  worktree: string;
  listFiles(): IndexedFile[];
  getIndexStatus(): IndexStatus;
  /** Files that were skipped or failed in the current indexing run. */
  getSkipped(): string[];
  gitInfo?: (worktree: string) => GitInfo;
  now?: () => Date;
}

export function readGitInfo(worktree: string): GitInfo {
  const git = (...args: string[]) => {
    try {
      return execFileSync("git", args, { cwd: worktree, stdio: ["ignore", "pipe", "ignore"], timeout: 5000 }).toString().trim() || "unknown";
    } catch {
      return "unknown";
    }
  };
  return { branch: git("rev-parse", "--abbrev-ref", "HEAD"), commit: git("rev-parse", "--short", "HEAD") };
}

interface Node {
  dirs: Map<string, Node>;
  files: IndexedFile[];
}

const plural = (n: number, word: string) => `${n} ${word}${n === 1 ? "" : "s"}`;

export function renderIndexTree(files: IndexedFile[], meta: IndexTreeMeta): string {
  const root: Node = { dirs: new Map(), files: [] };
  for (const file of files) {
    const parts = file.relativePath.split("/");
    let node = root;
    for (const dir of parts.slice(0, -1)) {
      if (!node.dirs.has(dir)) node.dirs.set(dir, { dirs: new Map(), files: [] });
      node = node.dirs.get(dir)!;
    }
    node.files.push(file);
  }
  const lines: string[] = [];
  const walk = (node: Node, depth: number) => {
    const pad = "  ".repeat(depth);
    for (const [name, child] of [...node.dirs].sort(([a], [b]) => a.localeCompare(b))) {
      lines.push(`${pad}- ${name}/`);
      walk(child, depth + 1);
    }
    for (const f of [...node.files].sort((a, b) => a.relativePath.localeCompare(b.relativePath))) {
      lines.push(`${pad}- ${basename(f.relativePath)} (${f.language}, ${plural(f.chunkCount, "chunk")})`);
    }
  };
  walk(root, 0);
  const out = [
    "# Indexed files",
    "",
    "<!-- generated by ai-context-opencode-plugin; do not edit -->",
    "",
    `- Repository: ${meta.repoName} (${meta.repoPath})`,
    `- Branch: ${meta.branch} (${meta.commit})`,
    `- Exported: ${meta.exportedAt}`,
    `- Index last updated: ${meta.newestIndexedAt ?? "never"}`,
    `- Files: ${files.length} · Chunks: ${meta.chunkCount}`,
    "",
    "## Tree",
    "",
    ...(lines.length ? lines : ["_nothing indexed yet_"]),
  ];
  if (meta.skipped.length) {
    out.push("", "## Not indexed", "", ...meta.skipped.map((s) => `- ${s}`));
  }
  return out.join("\n") + "\n";
}

export function writeIndexTree(deps: IndexTreeDeps): { filePath: string; fileCount: number } {
  const files = deps.listFiles();
  const status = deps.getIndexStatus();
  const git = (deps.gitInfo ?? readGitInfo)(deps.worktree);
  const md = renderIndexTree(files, {
    repoName: basename(deps.worktree),
    repoPath: deps.worktree,
    branch: git.branch,
    commit: git.commit,
    exportedAt: (deps.now ?? (() => new Date()))().toISOString(),
    newestIndexedAt: status.newestIndexedAt,
    chunkCount: status.chunkCount,
    skipped: deps.getSkipped(),
  });
  mkdirSync(dirname(deps.filePath), { recursive: true });
  writeFileSync(deps.filePath, md);
  return { filePath: deps.filePath, fileCount: files.length };
}

export function createExportIndexTreeTool(deps: IndexTreeDeps) {
  return tool({
    description: [
      "Write a Markdown tree of every file the index contains (language and",
      "chunk count per file) to .opencode/ai-context/index-tree.md, with the",
      "export date, repository, git branch/commit and last index update. Use it",
      "when the user asks which files or paths are indexed or what is indexed.",
      "The file is also refreshed after each completed indexing run.",
    ].join(" "),
    args: {},
    async execute() {
      const { filePath, fileCount } = writeIndexTree(deps);
      return `Wrote ${plural(fileCount, "file")} to ${filePath}`;
    },
  });
}
